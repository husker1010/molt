"""Participant-level nested cross-validation folds.

One outer assignment of ``n_outer`` folds is generated by iterative multi-label
stratification over endpoint status, 24-month event status, stage group, modality
availability, cohort membership and an optional extra indicator. Inside every outer
training set ``n_inner`` folds are generated with the same algorithm. The assignment is
deterministic given the seed and is stored once per development universe, so that every
endpoint, mode, comparator and ablation is evaluated on identical held-out participants.

On disk the folds are a parquet table with one row per participant::

    participant_id | cohort | outer_fold | inner_fold_0 | inner_fold_1 | ...

where ``inner_fold_{k}`` is the inner fold of the participant inside outer training set
``k`` (``-1`` when the participant belongs to outer test fold ``k``). A JSON sidecar
records the seed, the fold counts and the stratification columns.
"""

from __future__ import annotations

import json
import os
import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from molt.utils.seed import DEFAULT_SEED, derive_seed

__all__ = [
    "NestedFolds",
    "default_splits_path",
    "load_or_create_folds",
    "make_nested_folds",
    "stratification_matrix",
    "stratified_folds",
    "summarize_folds",
]

STAGES = ("I", "II", "III", "IV")


def _bool(series: pd.Series) -> np.ndarray:
    return pd.to_numeric(series, errors="coerce").fillna(0).to_numpy() > 0


def stratification_matrix(
    table: pd.DataFrame,
    *,
    endpoints: Sequence[str] = ("egfr_status", "pfi_event", "os_event"),
    horizon_months: float = 24.0,
    time_col: str = "pfi_time",
    event_col: str = "pfi_event",
    stage_col: str = "stage_group",
    modality_cols: Sequence[str] = ("has_rna", "has_ct"),
    extra: str | np.ndarray | pd.Series | None = None,
    cohort_col: str = "cohort",
) -> pd.DataFrame:
    """Binary label matrix used for multi-label stratification.

    Columns (constant columns are dropped):

    * ``<endpoint>_pos`` and ``<endpoint>_known`` for every endpoint column present,
    * ``event_<h>m``: event at or before ``horizon_months`` (``time_col``/``event_col``),
    * ``stage_<I..IV>``: one-hot stage group,
    * every modality-availability column present (e.g. ``has_rna``, ``has_ct``),
    * ``cohort_<id>`` when more than one cohort is present,
    * ``extra``: an optional indicator given as a column name, a regular expression on
      ``participant_id`` (prefix ``re:``) or a boolean array.

    Args:
        table: One row per participant (``participant_id`` as column or index).
    """
    df = table.reset_index() if "participant_id" not in table.columns else table
    cols: dict[str, np.ndarray] = {}
    for name in endpoints:
        if name in df.columns:
            values = pd.to_numeric(df[name], errors="coerce")
            cols[f"{name}_pos"] = (values == 1).to_numpy()
            cols[f"{name}_known"] = values.notna().to_numpy()
    if time_col in df.columns and event_col in df.columns:
        t = pd.to_numeric(df[time_col], errors="coerce")
        e = pd.to_numeric(df[event_col], errors="coerce")
        cols[f"event_{int(horizon_months)}m"] = ((t <= horizon_months) & (e == 1)).to_numpy()
    if stage_col in df.columns:
        stage = df[stage_col].astype("object")
        for s in STAGES:
            cols[f"stage_{s}"] = (stage == s).to_numpy()
    for name in modality_cols:
        if name in df.columns:
            cols[name] = _bool(df[name])
    if cohort_col in df.columns and df[cohort_col].nunique() > 1:
        for c in sorted(df[cohort_col].astype(str).unique()):
            cols[f"cohort_{c}"] = (df[cohort_col].astype(str) == c).to_numpy()
    if extra is not None:
        if isinstance(extra, str) and extra.startswith("re:"):
            rx = re.compile(extra[3:])
            cols["extra"] = (
                df["participant_id"].astype(str).map(lambda v: bool(rx.search(v))).to_numpy()
            )
        elif isinstance(extra, str):
            cols["extra"] = _bool(df[extra])
        else:
            cols["extra"] = np.asarray(extra, dtype=bool).reshape(-1)
    out = pd.DataFrame(cols, index=df["participant_id"].astype(str).to_numpy()).astype(bool)
    keep = [c for c in out.columns if 0 < out[c].sum() < len(out)]
    return out[keep]


def stratified_folds(labels: np.ndarray | pd.DataFrame, n_splits: int, seed: int) -> np.ndarray:
    """Assign rows to ``n_splits`` folds by iterative multi-label stratification.

    Falls back to a seeded random permutation when there are no informative labels.
    """
    y = np.asarray(labels, dtype=int)
    n = y.shape[0]
    if n < n_splits:
        raise ValueError(f"Cannot split {n} participants into {n_splits} folds")
    folds = np.full(n, -1, dtype=int)
    rng = np.random.default_rng(seed)
    if y.ndim != 2 or y.shape[1] == 0:
        folds[rng.permutation(n)] = np.arange(n) % n_splits
        return folds
    from iterstrat.ml_stratifiers import MultilabelStratifiedKFold

    splitter = MultilabelStratifiedKFold(
        n_splits=n_splits, shuffle=True, random_state=int(seed % (2**32 - 1))
    )
    for k, (_, test) in enumerate(splitter.split(np.zeros((n, 1)), y)):
        folds[test] = k
    return folds


@dataclass
class NestedFolds:
    """Outer and inner fold assignment of a development universe.

    Attributes:
        frame: Table with ``participant_id``, ``cohort``, ``outer_fold`` and one
            ``inner_fold_{k}`` column per outer fold.
        n_outer: Number of outer folds.
        n_inner: Number of inner folds per outer training set.
        seed: Seed of the assignment.
        meta: Free-form provenance (stratification columns, counts).
    """

    frame: pd.DataFrame
    n_outer: int
    n_inner: int
    seed: int = DEFAULT_SEED
    meta: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        self.frame = self.frame.copy()
        self.frame["participant_id"] = self.frame["participant_id"].astype(str)
        self.frame = self.frame.set_index("participant_id", drop=False)
        self.frame.index.name = None

    @staticmethod
    def inner_column(outer: int) -> str:
        """Name of the inner-fold column of outer fold ``outer``."""
        return f"inner_fold_{outer}"

    @property
    def participants(self) -> list[str]:
        return self.frame["participant_id"].tolist()

    def outer_test(self, k: int) -> list[str]:
        """Participants of outer test fold ``k``."""
        return self.frame.index[self.frame["outer_fold"] == k].tolist()

    def outer_train(self, k: int) -> list[str]:
        """Participants of outer training set ``k``."""
        return self.frame.index[self.frame["outer_fold"] != k].tolist()

    def inner_val(self, k: int, j: int) -> list[str]:
        """Inner validation fold ``j`` within outer training set ``k``."""
        return self.frame.index[self.frame[self.inner_column(k)] == j].tolist()

    def inner_train(self, k: int, j: int) -> list[str]:
        """Inner training set ``j`` within outer training set ``k``."""
        col = self.frame[self.inner_column(k)]
        return self.frame.index[(col >= 0) & (col != j)].tolist()

    def inner_fold_of(self, k: int, ids: Iterable[str]) -> np.ndarray:
        """Inner fold index (within outer training set ``k``) of each id."""
        return self.frame.loc[list(ids), self.inner_column(k)].to_numpy(dtype=int)

    def outer_fold_of(self, ids: Iterable[str]) -> np.ndarray:
        """Outer fold index of each id."""
        return self.frame.loc[list(ids), "outer_fold"].to_numpy(dtype=int)

    def restrict(self, ids: Iterable[str]) -> NestedFolds:
        """Folds restricted to ``ids`` (analytic sets are restrictions of the universe)."""
        keep = self.frame.index.intersection(pd.Index(list(map(str, ids))), sort=False)
        return NestedFolds(
            self.frame.loc[keep].reset_index(drop=True),
            self.n_outer,
            self.n_inner,
            self.seed,
            dict(self.meta),
        )

    def counts(self, table: pd.DataFrame, columns: Sequence[str]) -> pd.DataFrame:
        """Positives/events of ``columns`` per outer test fold (``table`` indexed by id)."""
        joined = table.reindex(self.frame.index)
        rows = []
        for k in range(self.n_outer):
            sel = joined[self.frame["outer_fold"].to_numpy() == k]
            row: dict[str, Any] = {"outer_fold": k, "n": len(sel)}
            for c in columns:
                if c in sel.columns:
                    row[c] = int((pd.to_numeric(sel[c], errors="coerce") == 1).sum())
            rows.append(row)
        return pd.DataFrame(rows)

    def save(self, path: str | os.PathLike[str]) -> Path:
        """Write the parquet table and its JSON sidecar (``<path>.json``)."""
        out = Path(path)
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_suffix(out.suffix + ".tmp")
        self.frame.reset_index(drop=True).to_parquet(tmp, index=False)
        os.replace(tmp, out)
        sidecar = {"n_outer": self.n_outer, "n_inner": self.n_inner, "seed": self.seed, **self.meta}
        out.with_suffix(".json").write_text(json.dumps(sidecar, indent=2, default=str) + "\n")
        return out

    @classmethod
    def load(cls, path: str | os.PathLike[str]) -> NestedFolds:
        """Read folds written by :meth:`save`."""
        path = Path(path)
        frame = pd.read_parquet(path)
        sidecar_path = path.with_suffix(".json")
        meta = json.loads(sidecar_path.read_text()) if sidecar_path.exists() else {}
        n_outer = int(meta.pop("n_outer", frame["outer_fold"].max() + 1))
        inner_cols = [c for c in frame.columns if re.fullmatch(r"inner_fold_\d+", c)]
        n_inner = int(meta.pop("n_inner", max(int(frame[c].max()) for c in inner_cols) + 1))
        seed = int(meta.pop("seed", DEFAULT_SEED))
        return cls(frame, n_outer, n_inner, seed, meta)


def make_nested_folds(
    table: pd.DataFrame,
    *,
    n_outer: int = 5,
    n_inner: int = 3,
    seed: int = DEFAULT_SEED,
    **strat_kwargs: Any,
) -> NestedFolds:
    """Create the nested fold assignment of ``table`` (one row per participant).

    Args:
        table: Participant table with ``participant_id`` (column or index) and the columns
            used by :func:`stratification_matrix`; ``cohort`` is carried into the output.
        n_outer: Number of outer folds.
        n_inner: Number of inner folds inside each outer training set.
        seed: Base seed; the inner assignment of outer fold ``k`` uses a seed derived from
            ``seed`` and ``k``.
        **strat_kwargs: Passed to :func:`stratification_matrix`.
    """
    df = (
        table.reset_index()
        if "participant_id" not in table.columns
        else table.reset_index(drop=True)
    )
    df = df.drop_duplicates("participant_id").reset_index(drop=True)
    labels = stratification_matrix(df, **strat_kwargs)
    outer = stratified_folds(labels.to_numpy(), n_outer, derive_seed(seed, "outer"))
    frame = pd.DataFrame(
        {
            "participant_id": df["participant_id"].astype(str).to_numpy(),
            "cohort": df["cohort"].astype(str).to_numpy() if "cohort" in df else "unknown",
            "outer_fold": outer,
        }
    )
    for k in range(n_outer):
        col = np.full(len(df), -1, dtype=int)
        train = np.flatnonzero(outer != k)
        sub = labels.iloc[train]
        sub = sub.loc[:, (sub.sum() > 0) & (sub.sum() < len(sub))]
        col[train] = stratified_folds(sub.to_numpy(), n_inner, derive_seed(seed, "inner", k))
        frame[NestedFolds.inner_column(k)] = col
    meta = {
        "stratification_columns": list(labels.columns),
        "n_participants": len(frame),
        "cohorts": sorted(frame["cohort"].unique().tolist()),
    }
    return NestedFolds(frame, n_outer, n_inner, seed, meta)


def default_splits_path(
    splits_dir: str | os.PathLike[str],
    cohorts: Sequence[str],
    n_outer: int,
    n_inner: int,
    seed: int,
) -> Path:
    """Canonical file name of a fold assignment.

    The shared 5 x 3 assignment with the default seed is ``<cohorts>.parquet`` (e.g.
    ``tcga_luad.parquet``); other settings add a suffix, e.g.
    ``tcga_luad_o2_i2_s1.parquet``. Several cohorts are joined with ``+``.
    """
    name = "+".join(sorted(cohorts))
    if (n_outer, n_inner, seed) != (5, 3, DEFAULT_SEED):
        name = f"{name}_o{n_outer}_i{n_inner}_s{seed}"
    return Path(splits_dir) / f"{name}.parquet"


def load_or_create_folds(
    table: pd.DataFrame,
    path: str | os.PathLike[str],
    *,
    n_outer: int = 5,
    n_inner: int = 3,
    seed: int = DEFAULT_SEED,
    rebuild: bool = False,
    **strat_kwargs: Any,
) -> NestedFolds:
    """Load the fold assignment at ``path`` or create and save it.

    An existing file is reused only if it was created with the same fold counts and seed
    and covers every participant of ``table``; otherwise a ``ValueError`` is raised unless
    ``rebuild`` is set, in which case the file is regenerated.
    """
    path = Path(path)
    ids = table.index if "participant_id" not in table.columns else table["participant_id"]
    ids = pd.Index(ids.astype(str))
    if path.exists() and not rebuild:
        folds = NestedFolds.load(path)
        missing = ids.difference(pd.Index(folds.participants))
        same = (folds.n_outer, folds.n_inner, folds.seed) == (n_outer, n_inner, seed)
        if same and missing.empty:
            return folds.restrict(ids)
        raise ValueError(
            f"Existing folds at {path} do not match the development universe "
            f"({len(missing)} participant(s) missing, settings match={same}); "
            "pass rebuild=True to regenerate them."
        )
    folds = make_nested_folds(table, n_outer=n_outer, n_inner=n_inner, seed=seed, **strat_kwargs)
    folds.save(path)
    return folds


def summarize_folds(folds: NestedFolds, table: pd.DataFrame, columns: Mapping[str, str]) -> dict:
    """Per-fold positives/events for reporting (``columns`` maps report name -> column)."""
    counts = folds.counts(table, list(columns.values()))
    return {name: counts[col].tolist() for name, col in columns.items() if col in counts}
